package com.sundaytools.app.ocr

import android.graphics.Bitmap
import com.google.mlkit.vision.common.InputImage
import com.google.mlkit.vision.text.Text
import com.google.mlkit.vision.text.TextRecognition
import com.google.mlkit.vision.text.TextRecognizer
import com.google.mlkit.vision.text.chinese.ChineseTextRecognizerOptions
import com.google.mlkit.vision.text.japanese.JapaneseTextRecognizerOptions
import com.google.mlkit.vision.text.korean.KoreanTextRecognizerOptions
import com.google.mlkit.vision.text.latin.TextRecognizerOptions
import kotlinx.coroutines.tasks.await
import javax.inject.Inject
import javax.inject.Singleton

/** Result of a successful scan: the player's display name (if found) and their tag. */
data class ScannedPlayer(val name: String?, val tag: String)

/** "Name - Tag" when a name was captured, otherwise just the tag. */
val ScannedPlayer.displayLabel: String
    get() = if (name != null) "$name - $tag" else tag

/**
 * Wraps Google ML Kit's on-device text recognizers and applies a heuristic
 * that isolates the player's name and tag from everything else visible on
 * screen.
 *
 * Sunday City's "tap a player" popup shows the display name on its own line,
 * followed by a line like "Lvl 2854 ess40" that combines the level and the
 * tag. We look for that "Lvl <number> <tag>" shape specifically (most
 * reliable, using the Latin recognizer since the tag itself is always plain
 * alnum), and take the name from the line directly above it.
 *
 * The NAME can be in scripts the Latin recognizer doesn't cover -- Chinese,
 * Japanese, or Korean. (Cyrillic/Greek names are already handled by the
 * Latin recognizer, which covers most European scripts.) If the Latin pass
 * doesn't find a name line, we retry just for the name using the
 * script-specific recognizers, in turn, and keep the first non-empty result.
 * Note this can't help with purely decorative "fancy text" fonts (the kind
 * generated by sites like LingoJam or EmojiCombos) -- those use unusual
 * Unicode symbols rather than an actual script, which no OCR model is
 * trained on. For that case the Save dialog lets the player's name be typed
 * in manually.
 *
 * When the caller (see [com.sundaytools.app.overlay.OverlayBubbleService]) has a
 * "capture area" configured in Settings, the bitmap passed in here is already
 * cropped to that region, which is by far the most reliable way to avoid
 * picking up unrelated text. As a second line of defense even within a
 * cropped region, [durationLikePattern] rejects strings shaped like a
 * countdown timer (e.g. "11h52m", "45m", "2h15m30s"), since those are not
 * valid player tags but can otherwise slip past [tagPattern].
 */
@Singleton
class TagOcrProcessor @Inject constructor() {

    private val latinRecognizer: TextRecognizer =
        TextRecognition.getClient(TextRecognizerOptions.DEFAULT_OPTIONS)

    private val chineseRecognizer: TextRecognizer by lazy {
        TextRecognition.getClient(ChineseTextRecognizerOptions.Builder().build())
    }
    private val japaneseRecognizer: TextRecognizer by lazy {
        TextRecognition.getClient(JapaneseTextRecognizerOptions.Builder().build())
    }
    private val koreanRecognizer: TextRecognizer by lazy {
        TextRecognition.getClient(KoreanTextRecognizerOptions.Builder().build())
    }

    /** Regex for a plausible player tag: 3-12 letters/digits, no whitespace or punctuation. */
    private val tagPattern = Regex("^[A-Za-z0-9]{3,12}$")

    /** Matches duration/countdown-shaped text like "11h52m", "45m", "2h15m30s", "1h". */
    private val durationLikePattern = Regex("^(\\d+[dhms])+$", RegexOption.IGNORE_CASE)

    /** Matches a "Lvl <number> <tag>" line, e.g. "Lvl 2854 ess40" or "Lvl. 2854   ess40". */
    private val levelTagPattern = Regex("(?i)lvl\\.?\\s*\\d+\\s+([A-Za-z0-9]{3,12})\\b")

    private data class LineInfo(val text: String, val top: Int)

    /**
     * Runs OCR on [bitmap] and returns the best candidate player name+tag, or
     * null if nothing matching the expected shapes was found.
     */
    suspend fun extractPlayerInfo(bitmap: Bitmap): ScannedPlayer? {
        val latinLines = collectLines(latinRecognizer, bitmap)
        if (latinLines.isEmpty()) return null

        val sortedLines = latinLines.sortedBy { it.top }

        // 1) Preferred: find the "Lvl <number> <tag>" line and take the name
        // from the line immediately above it.
        for ((index, lineInfo) in sortedLines.withIndex()) {
            val collapsed = lineInfo.text.replace(Regex("\\s+"), " ")
            val match = levelTagPattern.find(collapsed) ?: continue
            val candidateTag = match.groupValues[1]
            if (!tagPattern.matches(candidateTag) || durationLikePattern.matches(candidateTag)) {
                continue
            }

            var name = sortedLines.getOrNull(index - 1)
                ?.text
                ?.takeIf { it.isNotBlank() && !it.contains(Regex("(?i)lvl")) }

            // The Latin recognizer won't pick up Chinese/Japanese/Korean names,
            // so if it found the tag line but no name above it, retry just for
            // the name using each script-specific recognizer in turn.
            if (name == null) {
                name = findNameAboveWithFallbackRecognizers(bitmap, anchorTop = lineInfo.top)
            }

            return ScannedPlayer(name = name, tag = candidateTag)
        }

        // 2) Fallback: scan every line for anything shaped like a tag, no name.
        val candidates = mutableListOf<String>()
        for (lineInfo in sortedLines) {
            val cleaned = lineInfo.text.replace(" ", "")
            if (tagPattern.matches(cleaned) && !durationLikePattern.matches(cleaned)) {
                candidates.add(cleaned)
            }
        }
        if (candidates.isEmpty()) return null

        // Prefer candidates that mix letters and digits, since pure numbers or pure
        // words are more likely to be scores, timers, or unrelated UI labels.
        val mixedAlphaNumeric = candidates.filter { candidate ->
            candidate.any { it.isDigit() } && candidate.any { it.isLetter() }
        }
        val tag = mixedAlphaNumeric.firstOrNull() ?: candidates.first()
        return ScannedPlayer(name = null, tag = tag)
    }

    /**
     * Retries recognition with the Chinese, then Japanese, then Korean
     * recognizer, looking for a text line just above [anchorTop] (the tag
     * line's vertical position) in that recognizer's own results. Returns the
     * first non-blank match found.
     */
    private suspend fun findNameAboveWithFallbackRecognizers(bitmap: Bitmap, anchorTop: Int): String? {
        for (recognizer in listOf(chineseRecognizer, japaneseRecognizer, koreanRecognizer)) {
            val lines = runCatching { collectLines(recognizer, bitmap) }.getOrNull() ?: continue
            val candidate = lines
                .filter { it.top < anchorTop }
                .maxByOrNull { it.top }
                ?.text
                ?.takeIf { it.isNotBlank() }
            if (candidate != null) {
                return candidate
            }
        }
        return null
    }

    private suspend fun collectLines(recognizer: TextRecognizer, bitmap: Bitmap): List<LineInfo> {
        val image = InputImage.fromBitmap(bitmap, 0)
        val result: Text = recognizer.process(image).await()
        val lines = mutableListOf<LineInfo>()
        for (block in result.textBlocks) {
            for (line in block.lines) {
                val top = line.boundingBox?.top ?: continue
                val text = line.text.trim()
                if (text.isNotEmpty()) {
                    lines.add(LineInfo(text, top))
                }
            }
        }
        return lines
    }

    fun close() {
        latinRecognizer.close()
        chineseRecognizer.close()
        japaneseRecognizer.close()
        koreanRecognizer.close()
    }
}
