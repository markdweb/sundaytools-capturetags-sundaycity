/**
 * Displays the "Player Name / Tag / Status / Save / Copy Again / Cancel"
 * popup directly over the game. Hosted the same way as the bubble: a
 * ComposeView added straight to WindowManager.
 *
 * The Name field is editable: OCR can't reliably read stylized Unicode
 * "fancy text" fonts (the kind generated by sites like LingoJam or
 * EmojiCombos), so this lets the user type/fix the name by hand when OCR
 * gets it wrong or misses it entirely. The Status toggle (Blacklisted /
 * Thrower) picks what gets recorded both locally and on the shared Google
 * Sheet -- it can still be corrected later from the Today's Tags table.
 */
class SaveDialogController(
    private val context: Context,
    private val windowManager: WindowManager,
    lifecycleOwner: LifecycleOwner,
    viewModelStoreOwner: ViewModelStoreOwner,
    savedStateRegistryOwner: SavedStateRegistryOwner,
    private val playerName: String?,
    private val playerTag: String,
    private val onSave: (editedName: String?, status: String) -> Unit,
    private val onCopyAgain: (currentName: String?) -> Unit,
    private val onDismiss: () -> Unit,
    private val darkTheme: Boolean
) {
    private val layoutParams = WindowManager.LayoutParams(
        WindowManager.LayoutParams.WRAP_CONTENT,
        WindowManager.LayoutParams.WRAP_CONTENT,
        BubbleViewController.overlayWindowType(),
        WindowManager.LayoutParams.FLAG_DIM_BEHIND,
        PixelFormat.TRANSLUCENT
    ).apply {
        gravity = Gravity.CENTER
        dimAmount = 0.4f
    }

    private val composeView = ComposeView(context).apply {
        setViewTreeLifecycleOwner(lifecycleOwner)
        setViewTreeViewModelStoreOwner(viewModelStoreOwner)
        setViewTreeSavedStateRegistryOwner(savedStateRegistryOwner)
        setContent {
            SundayToolsTheme(darkTheme = darkTheme) {
                SaveDialogContent(
                    initialName = playerName,
                    tag = playerTag,
                    onSave = onSave,
                    onCopyAgain = onCopyAgain,
                    onCancel = { dismiss() }
                )
            }
        }
    }

    fun show() {
        runCatching { windowManager.addView(composeView, layoutParams) }
    }

    fun dismiss() {
        runCatching { windowManager.removeView(composeView) }
        onDismiss()
    }
}

private val STATUS_OPTIONS = listOf("Blacklisted", "Thrower")

@Composable
private fun SaveDialogContent(
    initialName: String?,
    tag: String,
    onSave: (String?, String) -> Unit,
    onCopyAgain: (String?) -> Unit,
    onCancel: () -> Unit
) {
    var name by remember(initialName) { mutableStateOf(initialName.orEmpty()) }
    var status by remember { mutableStateOf(STATUS_OPTIONS.first()) }

    Card(
        shape = RoundedCornerShape(20.dp),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
        modifier = Modifier.padding(24.dp)
    ) {
        Column(
            modifier = Modifier.padding(24.dp),
            horizontalAlignment = androidx.compose.ui.Alignment.CenterHorizontally
        ) {
            Text(
                text = "Player Tag",
                style = MaterialTheme.typography.labelLarge,
                color = MaterialTheme.colorScheme.onSurfaceVariant
            )
            Text(
                text = tag,
                style = MaterialTheme.typography.headlineMedium,
                fontWeight = FontWeight.Bold,
                modifier = Modifier.padding(top = 4.dp, bottom = 16.dp)
            )

            OutlinedTextField(
                value = name,
                onValueChange = { name = it },
                label = { Text("Player Name (edit if not detected)") },
                singleLine = true,
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(bottom = 16.dp)
            )

            Text(
                text = "Status",
                style = MaterialTheme.typography.labelLarge,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(bottom = 6.dp)
            )
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(bottom = 16.dp),
                horizontalArrangement = Arrangement.spacedBy(8.dp)
            ) {
                STATUS_OPTIONS.forEach { option ->
                    val selected = option == status
                    Button(
                        onClick = { status = option },
                        modifier = Modifier.weight(1f),
                        colors = if (selected) {
                            ButtonDefaults.buttonColors()
                        } else {
                            ButtonDefaults.outlinedButtonColors()
                        }
                    ) {
                        Text(option)
                    }
                }
            }

            Button(
                onClick = { onSave(name.trim().ifBlank { null }, status) },
                modifier = Modifier.fillMaxWidth()
            ) {
                Text("Save")
            }

            OutlinedButton(
                onClick = { onCopyAgain(name.trim().ifBlank { null }) },
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(top = 10.dp)
            ) {
                Text("Copy Again")
            }

            TextButton(
                onClick = onCancel,
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(top = 4.dp)
            ) {
                Text("Cancel")
            }
        }
    }
}
